-- Strategy (Path 2 — synthetic email + Supabase Auth):
--   • Students get a synthetic email like `marcus-j.cdsi-2026-a@cdsi.local`
--     and a 4-digit PIN as their Supabase Auth password.
--   • Teachers use real email + password (Supabase Auth email/password flow).
--   • All existing RLS keeps working because auth.uid() still resolves.
--
-- This migration only adds *app-level metadata* (pin_set, lockout, class
-- bootstrap). The actual auth credentials live in auth.users (managed by
-- Supabase Auth) and we never touch them directly except via the admin API.
