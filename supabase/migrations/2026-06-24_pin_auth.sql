-- ---------- profiles: add columns for PIN flow ------------------------------

alter table public.profiles
  add column if not exists pin_set boolean not null default false,
  add column if not exists pin_failed_attempts integer not null default 0,
  add column if not exists pin_locked_at timestamptz,
  add column if not exists primary_class_id uuid references public.classes(id) on delete set null;

comment on column public.profiles.pin_set is
  'TRUE once the student has chosen their PIN (first login flow complete).';
comment on column public.profiles.pin_failed_attempts is
  'Consecutive wrong PIN attempts. Reset to 0 on success. Locked at 5.';
comment on column public.profiles.pin_locked_at is
  'When student was locked out (5 wrong PINs). NULL = not locked.';
comment on column public.profiles.primary_class_id is
  'Which class the student logs in under. Drives the class-code → roster flow.';

-- ---------- classes: ensure short, human-typeable join codes ----------------
-- Existing schema allows any unique text. We don't change existing codes,
-- but new ones generated by the server action will follow CDSI-2026-A pattern.

-- ---------- RLS additions ---------------------------------------------------
-- Students need to be able to read the names of OTHER students in their class
-- during the login flow (so they can pick their name from a grid). But the
-- login flow runs BEFORE the student has auth.uid() — they haven't signed in
-- yet. So the roster-fetch must use the service-role key (server action only).
--
-- We don't open new client-readable policies. Server actions using the admin
-- client bypass RLS for the login bootstrap.

