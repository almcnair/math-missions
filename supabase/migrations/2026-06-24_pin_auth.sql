-- ---------- helper: generate a join code ------------------------------------

create or replace function public.generate_join_code()
returns text
language plpgsql
as $$
declare
  candidate text;
  attempts int := 0;
begin
  loop
    -- 6-char alphanumeric, no ambiguous chars (no 0/O, 1/I/L)
    candidate := upper(
      substr(
        translate(encode(gen_random_bytes(8), 'base64'), '/+=OIL01', ''),
        1, 6
      )
    );
    exit when length(candidate) = 6 and not exists (
      select 1 from public.classes where join_code = candidate
    );
    attempts := attempts + 1;
    if attempts > 50 then
      raise exception 'Could not generate unique join code after 50 attempts';
    end if;
  end loop;
  return candidate;
end;
$$;
