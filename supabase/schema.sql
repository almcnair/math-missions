create extension if not exists "pgcrypto";

-- ---------- Profiles (mirrors auth.users) -----------------------------------

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('student','teacher','admin')) default 'student',
  display_name text not null,
  email text not null unique,
  avatar_config jsonb not null default '{}'::jsonb,
  credits integer not null default 0,
  rank_xp integer not null default 0,
  streak integer not null default 0,
  created_at timestamptz not null default now()
);

-- ---------- Classes ---------------------------------------------------------

create table if not exists public.classes (
  id uuid primary key default gen_random_uuid(),
  teacher_id uuid not null references public.profiles(id) on delete cascade,
  name text not null,                -- "Period 4 - 7th Grade" or "MS Novice"
  join_code text not null unique,    -- 6-char shareable code
  division text check (division is null or division in ('ms','hs')),   -- lab division
  level    text check (level    is null or level    in ('novice','jv','varsity')),
  created_at timestamptz not null default now()
);

create index if not exists idx_classes_teacher on public.classes(teacher_id);

-- ---------- Class coaches (many-to-many) ------------------------------------
-- A lab can have multiple coaches. Membership grants full teacher-level
-- access to the class via is_class_teacher(). Equal status; no head/assistant
-- distinction (deferred until we actually need it).
create table if not exists public.class_coaches (
  class_id uuid not null references public.classes(id)   on delete cascade,
  coach_id uuid not null references public.profiles(id) on delete cascade,
  added_at timestamptz not null default now(),
  added_by uuid references public.profiles(id) on delete set null,
  primary key (class_id, coach_id)
);

create index if not exists idx_class_coaches_coach on public.class_coaches(coach_id);

-- ---------- Coach invite tokens (magic-link onboarding) ---------------------
-- Generated by admins on /coach/invites, claimed by coaches via /coach/join.
-- On claim: profile promoted to teacher + class_coaches row inserted.
create table if not exists public.coach_invite_tokens (
  token       text primary key,
  class_id    uuid not null references public.classes(id) on delete cascade,
  email       text,
  note        text,
  created_by  uuid references public.profiles(id) on delete set null,
  created_at  timestamptz not null default now(),
  expires_at  timestamptz not null,
  used_at     timestamptz,
  used_by     uuid references public.profiles(id) on delete set null
);

create index if not exists idx_coach_invite_tokens_class on public.coach_invite_tokens(class_id);
create index if not exists idx_coach_invite_tokens_open
  on public.coach_invite_tokens(expires_at)
  where used_at is null;

-- ---------- Enrollments -----------------------------------------------------

create table if not exists public.enrollments (
  id uuid primary key default gen_random_uuid(),
  class_id uuid not null references public.classes(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  unique(class_id, student_id)
);

create index if not exists idx_enrollments_student on public.enrollments(student_id);
create index if not exists idx_enrollments_class on public.enrollments(class_id);

-- ---------- Missions (catalog) ----------------------------------------------
-- The actual content lives in JSON files in the repo. This table is the catalog
-- the teacher dashboard reads when assigning. Keep in sync with /content/missions/.

create table if not exists public.missions (
  id text primary key,                 -- "inherency-v1" — matches JSON file
  campaign_id text not null,
  sector_id text not null,
  number integer not null,
  title text not null,
  subtitle text,
  difficulty text not null,
  estimated_minutes integer not null,
  prerequisites text[] not null default '{}',
  unlocks text[] not null default '{}',
  active boolean not null default true
);

-- ---------- Assignments -----------------------------------------------------

create table if not exists public.assignments (
  id uuid primary key default gen_random_uuid(),
  class_id uuid not null references public.classes(id) on delete cascade,
  mission_id text not null references public.missions(id),
  assigned_at timestamptz not null default now(),
  due_at timestamptz,
  required boolean not null default true,
  unique(class_id, mission_id)
);

create index if not exists idx_assignments_class on public.assignments(class_id);

-- ---------- Attempts (every CFU answer) -------------------------------------

create table if not exists public.attempts (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  class_id uuid not null references public.classes(id) on delete cascade,
  mission_id text not null references public.missions(id),
  slide_id text not null,
  type text not null,                  -- "cfu-mcq" etc.
  correct boolean not null,
  details jsonb not null,              -- shape varies by type, see mission-schema.ts
  started_at timestamptz not null,
  submitted_at timestamptz not null default now(),
  time_spent_ms integer not null
);

create index if not exists idx_attempts_student_mission on public.attempts(student_id, mission_id);
create index if not exists idx_attempts_class_mission on public.attempts(class_id, mission_id);
create index if not exists idx_attempts_mission_slide on public.attempts(mission_id, slide_id);

-- ---------- Completions (one per student per mission) -----------------------

create table if not exists public.completions (
  id uuid primary key default gen_random_uuid(),
  student_id uuid not null references public.profiles(id) on delete cascade,
  class_id uuid not null references public.classes(id) on delete cascade,
  mission_id text not null references public.missions(id),
  finished_at timestamptz not null default now(),
  credits_earned integer not null,
  accuracy numeric(4,3) not null,      -- 0.000–1.000
  shields_remaining integer not null,
  unique(student_id, mission_id)
);

create index if not exists idx_completions_class_mission on public.completions(class_id, mission_id);

