-- Helper functions for cross-table RLS checks. SECURITY DEFINER runs these as
-- the table owner, which is exempt from RLS by default — this is required
-- here because classes' and enrollments' SELECT policies each query the
-- other table; inlining those joins directly in the policy (instead of going
-- through one of these RLS-bypassing helpers) causes infinite recursion
-- (Postgres error 42P17) the moment either table is read.
-- See supabase/migrations/2026-06-24_fix_rls_recursion.sql.

-- Multi-coach aware: true if the caller owns the class OR is listed in
-- class_coaches. See 2026-07-07_labs_and_coach_invites.sql.
create or replace function public.is_class_teacher(p_class_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.classes
    where id = p_class_id and teacher_id = auth.uid()
  )
  or exists (
    select 1 from public.class_coaches
    where class_id = p_class_id and coach_id = auth.uid()
  );
$$;

create or replace function public.is_enrolled_in_class(p_class_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.enrollments where class_id = p_class_id and student_id = auth.uid()
  );
$$;

create or replace function public.is_teacher_of_student(p_student_id uuid)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.enrollments e
    join public.classes c on c.id = e.class_id
    where e.student_id = p_student_id and c.teacher_id = auth.uid()
  );
$$;

grant execute on function public.is_class_teacher(uuid)      to authenticated;
grant execute on function public.is_enrolled_in_class(uuid)  to authenticated;
grant execute on function public.is_teacher_of_student(uuid) to authenticated;

-- profiles: read own, teachers read students in their classes, admin all
create policy "own profile read"   on public.profiles for select using (auth.uid() = id);
create policy "own profile update" on public.profiles for update using (auth.uid() = id);
create policy "teacher reads class profiles" on public.profiles for select
  using (public.is_teacher_of_student(profiles.id));

-- classes: teachers see their own classes, students see classes they're in
create policy "teacher owns classes" on public.classes for all using (teacher_id = auth.uid());
create policy "student reads enrolled classes" on public.classes for select
  using (public.is_enrolled_in_class(classes.id));

-- class_coaches: coaches see their own membership rows. Writes are admin-only
-- (the invite-claim flow uses the service-role admin client to bypass RLS).
create policy "coach reads own class_coaches" on public.class_coaches for select
  using (coach_id = auth.uid());
create policy "admin writes class_coaches" on public.class_coaches for all
  using (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'));

-- coach_invite_tokens: admin-only (both reads and writes).
create policy "admin reads coach_invite_tokens" on public.coach_invite_tokens for select
  using (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'));
create policy "admin writes coach_invite_tokens" on public.coach_invite_tokens for all
  using (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'));

-- enrollments: student sees their own, teacher sees their classes'
create policy "student reads own enrollments" on public.enrollments for select using (student_id = auth.uid());
create policy "teacher reads class enrollments" on public.enrollments for select
  using (public.is_class_teacher(enrollments.class_id));
create policy "student joins class" on public.enrollments for insert with check (student_id = auth.uid());
create policy "teacher removes student" on public.enrollments for delete
  using (public.is_class_teacher(enrollments.class_id));

-- missions: anyone signed in can read the catalog
create policy "anyone reads missions" on public.missions for select using (auth.uid() is not null);

-- assignments: students see their class's, teachers manage their class's
create policy "student reads class assignments" on public.assignments for select
  using (public.is_enrolled_in_class(assignments.class_id));
create policy "teacher manages assignments" on public.assignments for all
  using (public.is_class_teacher(assignments.class_id));

-- attempts: students write their own, read their own; teachers read their class's
create policy "student writes own attempts" on public.attempts for insert with check (student_id = auth.uid());
create policy "student reads own attempts" on public.attempts for select using (student_id = auth.uid());
create policy "teacher reads class attempts" on public.attempts for select
  using (public.is_class_teacher(attempts.class_id));

-- completions: same pattern
create policy "student writes own completions" on public.completions for insert with check (student_id = auth.uid());
create policy "student reads own completions" on public.completions for select using (student_id = auth.uid());
create policy "teacher reads class completions" on public.completions for select
  using (public.is_class_teacher(completions.class_id));
